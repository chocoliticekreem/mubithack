STUDIO_LIMIT = 200_000


class OfflineStudio(Studio):
    """forge's real Studio.sync with the StudioMCP calls answered locally; the pull fetches like Studio would."""

    def __init__(self, settings, playing=False):
        super().__init__(settings)
        self.codes, self.playing, self.fetched, self.have = [], playing, [], set()

    async def state(self):
        self._playing = self.playing
        return {'playing': self.playing}

    async def execute_luau(self, code, datamodel='Edit', timeout=None):
        assert len(code) < STUDIO_LIMIT, f'{len(code)} chars would be refused by Studio'
        self.codes.append(code)
        if '-- MuMakePreflight' in code:
            return json.dumps({'ok': True})
        if '-- MuMakeMark' in code:
            return '40'
        port = re.search(r'BASE = "http://127\.0\.0\.1:(\d+)/"', code)[1]
        manifest = json.loads(re.search(r'MANIFEST_JSON: string\? = \[(=*)\[\n(.*?)\]\1\]', code, re.S)[2])
        inline = re.search(r'INLINE_JSON: string\? = \[(=*)\[\n(.*?)\]\1\]', code, re.S)
        inline = json.loads(inline[2]) if inline else {}
        defer, written = 'local DEFER = true' in code, []
        for entry in manifest:
            if entry['path'] in self.have:
                continue
            if entry['path'] not in inline:
                if defer:
                    continue
                with urlopen(f"http://127.0.0.1:{port}/{entry['path']}") as reply:
                    assert reply.read().decode() == (self.root / entry['path']).read_text()
                self.fetched.append(entry['path'])
            written.append(entry['path'])
        self.have.update(written)
        return f"OK {len(manifest)} files, changed: {', '.join(written) or 'none'}; skipped 0, fetched {len(self.fetched)}"



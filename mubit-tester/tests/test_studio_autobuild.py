def big_draft(settings, files=40, size=25_000):
    store = RunStore(settings, 'big-obby')
    store.ensure()
    modules = []
    for i in range(files):
        path = f'ServerScriptService/Stage{i:02d}.luau'
        (store.game_dir / path).parent.mkdir(parents=True, exist_ok=True)
        body = f'local M = {{}}\nM.n = {i}\n' + '-- stage data ' * (size // 14) + '\nreturn M\n'
        (store.game_dir / path).write_text(body)
        modules.append({'path': path, 'purpose': 'stage', 'depends': []})
    store.save_spec({'title': 'Big obby', 'modules': modules, 'mumake_project': 'big-obby'})
    store.save_state(store.new_state('a big obby'))
    return store


async def test_install_uses_the_chunked_sync_for_a_game_bigger_than_one_command(settings):
    store = big_draft(settings)
    total = sum(p.stat().st_size for p in store.game_dir.rglob('*.luau'))
    assert total > 4 * STUDIO_LIMIT
    studio = OfflineStudio(settings)
    studio.root = store.game_dir
    try:
        result = await install_draft(studio, settings, store.slug)
    finally:
        await studio.__aexit__(None, None, None)
    assert result['files'] == 40 and result['changed'] == 40
    assert '-- MuMakePreflight' in studio.codes[0] and '-- MuMakeMark' in studio.codes[-1]
    assert 'GENERATED by game/tools/sync.py' in studio.codes[1]
    assert not studio.fetched, 'no HTTP: Studio may refuse the pull its HttpEnabled write'
    assert 'big-obby' in studio.codes[-1] and len(studio.codes) > 3  # preflight, several sync calls, mark


async def test_install_refuses_while_studio_is_playing(settings):
    store = big_draft(settings, files=1, size=10)
    studio = OfflineStudio(settings, playing=True)
    with pytest.raises(ValueError, match='already running'):
        await install_draft(studio, settings, store.slug)
    assert studio.codes == []


async def test_install_refuses_a_published_place_and_broken_code(settings):
    store = big_draft(settings, files=1, size=10)
    with pytest.raises(ValueError, match='unpublished local game'):
        await install_draft(OfflineStudio(settings), settings, store.slug, place_id=123)
    (store.game_dir / 'ServerScriptService/Stage00.luau').write_text('local = = 1')
    studio = OfflineStudio(settings)
    with pytest.raises(ValueError, match='has errors'):
        await install_draft(studio, settings, store.slug)
    assert studio.codes == []


def iteration(**over):
    return {'n': 1, 'score': 8, 'errors': [], 'engine': 'headless', 'failed_steps': [], 'fixes': 1, **over}


@pytest.mark.parametrize('it,reason', [
    (iteration(), None),
    (iteration(score=6.5), 'score 6.5/10, needs 7'),
    (iteration(score=9, errors=['Stage 3: attempt to index nil']), '1 error in the last playtest'),
    (iteration(engine='none'), 'could not playtest'),
    (iteration(failed_steps=['playtest']), 'could not playtest'),
    (iteration(score=None), 'did not score'),
    (iteration(errors=['ServerScriptService/ForgeTest.server.luau:2151: attempt to perform arithmetic']), None),
])
def test_standard_needs_score_7_no_errors_and_a_real_playtest(settings, it, reason):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [it]
    store.save_state(state)
    out = standard(settings, store.slug, {'ready': True})
    assert out['ready'] is (reason is None)
    if reason:
        assert reason in out['reason']
    assert standard(settings, store.slug, {'ready': False, 'errors': ['Missing: x']})['reason'] == 'Missing: x'


async def test_no_rounds_when_the_first_playtest_already_meets_the_standard(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [iteration(score=8)]
    store.save_state(state)

    async def never(*a, **k):
        raise AssertionError('no round needed')
    monkeypatch.setattr(studio_builder, 'run_game', never)
    events = []

    async def install(slug):
        return {'files': 1, 'changed': 1}
    draft = await studio_builder.describe_draft(settings, store.slug)
    result = await finish_draft(settings, draft, lambda m, ok=None: events.append((m, ok)), install=install)
    assert result['standard']['ready'] and result['standard']['rounds'] == 0
    assert events[-1] == ('Ready: score 8/10 on the first playtest', True)


async def test_each_install_launches_the_game_and_the_last_one_keeps_it_running(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [iteration(score=8)]
    store.save_state(state)
    shows, events = [], []

    async def install(slug):
        return {'files': 1, 'changed': 1}

    async def show(slug, keep):
        shows.append(keep)
        if len(shows) == 1:
            return store.dir / 'iterations/1/screenshot.png'
        raise RuntimeError('Studio stayed disconnected')
    draft = await studio_builder.describe_draft(settings, store.slug)
    result = await finish_draft(settings, draft, lambda m, ok=None: events.append((m, ok)), install=install, show=show)
    assert shows == [False, True]
    assert ('Launched in Studio: new screenshot on the dashboard', True) in events
    assert ('Could not launch it in Studio: Studio stayed disconnected', False) in events
    assert result['standard']['ready']  # a screenshot problem never makes a good game "not ready"



import asyncio
import json
import re
from dataclasses import replace
from urllib.request import urlopen

import pytest

from forge.config import load_settings
from forge.memory import RunStore
from forge.studio import Studio
from mubit_tester import studio_builder
from mubit_tester.studio_builder import finish_draft, install_draft, standard

STUDIO_LIMIT = 200_000


class OfflineStudio(Studio):
    """forge's real Studio.sync with the StudioMCP calls answered locally; the pull fetches like Studio would."""

    def __init__(self, settings, playing=False):
        super().__init__(settings)
        self.codes, self.playing, self.fetched, self.have = [], playing, [], set()

    async def state(self):
        self._playing = self.playing
        return {'playing': self.playing}

    async def execute_luau(self, code, datamodel='Edit', timeout=None):
        assert len(code) < STUDIO_LIMIT, f'{len(code)} chars would be refused by Studio'
        self.codes.append(code)
        if '-- MuMakePreflight' in code:
            return json.dumps({'ok': True})
        if '-- MuMakeMark' in code:
            return '40'
        port = re.search(r'BASE = "http://127\.0\.0\.1:(\d+)/"', code)[1]
        manifest = json.loads(re.search(r'MANIFEST_JSON: string\? = \[(=*)\[\n(.*?)\]\1\]', code, re.S)[2])
        inline = re.search(r'INLINE_JSON: string\? = \[(=*)\[\n(.*?)\]\1\]', code, re.S)
        inline = json.loads(inline[2]) if inline else {}
        defer, written = 'local DEFER = true' in code, []
        for entry in manifest:
            if entry['path'] in self.have:
                continue
            if entry['path'] not in inline:
                if defer:
                    continue
                with urlopen(f"http://127.0.0.1:{port}/{entry['path']}") as reply:
                    assert reply.read().decode() == (self.root / entry['path']).read_text()
                self.fetched.append(entry['path'])
            written.append(entry['path'])
        self.have.update(written)
        return f"OK {len(manifest)} files, changed: {', '.join(written) or 'none'}; skipped 0, fetched {len(self.fetched)}"


@pytest.fixture
def settings(tmp_path):
    return replace(load_settings(), runs_dir=tmp_path / 'runs', sync_port=0)


def big_draft(settings, files=40, size=25_000):
    store = RunStore(settings, 'big-obby')
    store.ensure()
    modules = []
    for i in range(files):
        path = f'ServerScriptService/Stage{i:02d}.luau'
        (store.game_dir / path).parent.mkdir(parents=True, exist_ok=True)
        body = f'local M = {{}}\nM.n = {i}\n' + '-- stage data ' * (size // 14) + '\nreturn M\n'
        (store.game_dir / path).write_text(body)
        modules.append({'path': path, 'purpose': 'stage', 'depends': []})
    store.save_spec({'title': 'Big obby', 'modules': modules, 'mumake_project': 'big-obby'})
    store.save_state(store.new_state('a big obby'))
    return store


async def test_install_uses_the_chunked_sync_for_a_game_bigger_than_one_command(settings):
    store = big_draft(settings)
    total = sum(p.stat().st_size for p in store.game_dir.rglob('*.luau'))
    assert total > 4 * STUDIO_LIMIT
    studio = OfflineStudio(settings)
    studio.root = store.game_dir
    try:
        result = await install_draft(studio, settings, store.slug)
    finally:
        await studio.__aexit__(None, None, None)
    assert result['files'] == 40 and result['changed'] == 40
    assert '-- MuMakePreflight' in studio.codes[0] and '-- MuMakeMark' in studio.codes[-1]
    assert 'GENERATED by game/tools/sync.py' in studio.codes[1]
    assert not studio.fetched, 'no HTTP: Studio may refuse the pull its HttpEnabled write'
    assert 'big-obby' in studio.codes[-1] and len(studio.codes) > 3  # preflight, several sync calls, mark


async def test_install_refuses_while_studio_is_playing(settings):
    store = big_draft(settings, files=1, size=10)
    studio = OfflineStudio(settings, playing=True)
    with pytest.raises(ValueError, match='already running'):
        await install_draft(studio, settings, store.slug)
    assert studio.codes == []


async def test_install_refuses_a_published_place_and_broken_code(settings):
    store = big_draft(settings, files=1, size=10)
    with pytest.raises(ValueError, match='unpublished local game'):
        await install_draft(OfflineStudio(settings), settings, store.slug, place_id=123)
    (store.game_dir / 'ServerScriptService/Stage00.luau').write_text('local = = 1')
    studio = OfflineStudio(settings)
    with pytest.raises(ValueError, match='has errors'):
        await install_draft(studio, settings, store.slug)
    assert studio.codes == []


def iteration(**over):
    return {'n': 1, 'score': 8, 'errors': [], 'engine': 'headless', 'failed_steps': [], 'fixes': 1, **over}


@pytest.mark.parametrize('it,reason', [
    (iteration(), None),
    (iteration(score=5.5), 'score 5.5/10, needs 6'),
    (iteration(score=9, errors=['Stage 3: attempt to index nil']), '1 error in the last playtest'),
    (iteration(engine='none'), 'could not playtest'),
    (iteration(failed_steps=['playtest']), 'could not playtest'),
    (iteration(score=None), 'did not score'),
    (iteration(errors=['ServerScriptService/ForgeTest.server.luau:2151: attempt to perform arithmetic']), None),
])
def test_standard_needs_score_6_no_errors_and_a_real_playtest(settings, it, reason):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [it]
    store.save_state(state)
    out = standard(settings, store.slug, {'ready': True})
    assert out['ready'] is (reason is None)
    if reason:
        assert reason in out['reason']
    assert standard(settings, store.slug, {'ready': False, 'errors': ['Missing: x']})['reason'] == 'Missing: x'


async def test_no_rounds_when_the_first_playtest_already_meets_the_standard(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [iteration(score=8)]
    store.save_state(state)

    async def never(*a, **k):
        raise AssertionError('no round needed')
    monkeypatch.setattr(studio_builder, 'run_game', never)
    events = []

    async def install(slug):
        return {'files': 1, 'changed': 1}
    draft = await studio_builder.describe_draft(settings, store.slug)
    result = await finish_draft(settings, draft, lambda m, ok=None: events.append((m, ok)), install=install)
    assert result['standard']['ready'] and result['standard']['rounds'] == 0
    assert events[-1] == ('Ready: score 8/10 on the first playtest', True)


async def test_studio_refusing_the_install_means_not_ready(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [iteration(score=9)]
    store.save_state(state)

    async def install(slug):
        raise ValueError('A playtest is already running. Stop it in Studio first.')
    draft = await studio_builder.describe_draft(settings, store.slug)
    events = []
    result = await finish_draft(settings, draft, lambda m, ok=None: events.append((m, ok)), install=install)
    assert result['in_studio'] is False and result['standard']['ready'] is False
    assert 'Studio does not have this version' in result['standard']['reason']
    assert ('Not installed in Studio: A playtest is already running. Stop it in Studio first.', False) in events


async def test_a_failing_round_ends_the_rounds_with_its_reason(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    state = store.load_state()
    state['iterations'] = [iteration(score=4)]
    store.save_state(state)
    calls = []

    async def broken(*a, **k):
        calls.append(1)
        raise RuntimeError('Mubit is down')
    monkeypatch.setattr(studio_builder, 'run_game', broken)

    async def install(slug):
        return {'files': 1, 'changed': 0}
    draft = await studio_builder.describe_draft(settings, store.slug)
    result = await finish_draft(settings, draft, lambda *a: None, install=install)
    assert len(calls) == 1
    assert result['standard'] == {'ready': False, 'reason': 'Round 1 of 5 could not finish: RuntimeError: Mubit is down',
                                  'score': 4, 'errors': 0, 'rounds': 0}


async def test_cancel_mid_round_marks_progress_stopped(settings, monkeypatch):
    store = big_draft(settings, files=1, size=10)
    started = asyncio.Event()

    async def hang(*a, **k):
        started.set()
        await asyncio.Event().wait()
    monkeypatch.setattr(studio_builder, 'run_game', hang)

    async def install(slug):
        return {'files': 1, 'changed': 0}
    draft = await studio_builder.describe_draft(settings, store.slug)
    task = asyncio.create_task(finish_draft(settings, draft, lambda *a: None, install=install))
    await started.wait()
    task.cancel()
    with pytest.raises(asyncio.CancelledError):
        await task
    progress = json.loads((store.dir / 'progress.json').read_text())
    assert progress['running'] is False and progress['phase'] == 'failed'
    assert 75 <= progress['pct'] < 100
